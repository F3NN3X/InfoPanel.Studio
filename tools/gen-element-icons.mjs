#!/usr/bin/env node
// Writes src/lib/infopanel/elements/icons.generated.ts: the Icon element's lucide icons as their inner SVG
// markup, rendered here once so the kiosk bundle carries strings instead of every lucide component.
//   node tools/gen-element-icons.mjs
// Run it after changing ICONS below or updating lucide-react; tests/lib/infopanel/elements/icons.test.ts
// fails while the file is stale.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as lucide from "lucide-react";
import { innerMarkup } from "./gen-gauge-icons.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "src/lib/infopanel/elements/icons.generated.ts");

/** The icons a dashboard asks for: hardware, weather, media, status and a few decorations (lucide component names). */
export const ICONS = (
  "Activity AirVent AlarmClock ArrowDown ArrowDownUp ArrowUp AudioLines Battery BatteryCharging BatteryFull BatteryLow Bell " +
  "Bluetooth Bolt Box Brain Cable Calendar Camera ChartColumn ChartLine ChartPie Check CircleGauge CircuitBoard Clock Clock3 " +
  "Cloud CloudLightning CloudRain CloudSun Code Coffee Compass Container Cpu Crown Database Disc3 Download Droplet Droplets " +
  "Earth Eye Fan File Film Flag Flame Folder Gamepad2 Gauge Gem Ghost Globe Gpu HardDrive HardDriveDownload Headphones Heart " +
  "HeartPulse House Joystick Keyboard Laptop Layers Leaf Lightbulb Lock Mail MemoryStick MessageSquare Mic Microchip Monitor " +
  "Moon Mouse Music Network Pause Play Plug Power Printer Radio RefreshCw Rocket Router Satellite Server Settings Shield Signal " +
  "Skull Smartphone Snowflake Sparkles Speaker Square Star Sun Sunrise Sunset Swords Tablet Target Terminal Thermometer " +
  "ThermometerSnowflake ThermometerSun Timer Trophy TrendingDown TrendingUp Tv Umbrella Upload Usb User Video Volume2 VolumeX " +
  "Waves Wifi WifiOff Wind Wrench Zap"
).split(" ");

/** "HardDriveDownload" → "hard-drive-download", "Gamepad2" → "gamepad-2" (lucide's own file names). */
export const kebab = (name) =>
  name
    .replace(/([a-z])([A-Z0-9])/g, "$1-$2")
    .replace(/([0-9])([A-Z])/g, "$1-$2")
    .toLowerCase();

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const lines = ICONS.map((component) => {
    // biome-ignore lint/performance/noDynamicNamespaceImportAccess: a build-time script; the names come from ICONS.
    const Icon = lucide[component];
    if (!Icon) throw new Error(`lucide-react has no ${component}`);
    return `  ${JSON.stringify(kebab(component))}: ${JSON.stringify(innerMarkup(Icon))},`;
  });
  const out = `// Generated by tools/gen-element-icons.mjs; do not edit.\n// The Icon element's lucide icons (24 px grid, 2 px round strokes) as inner SVG markup, without the outer <svg>.\n\nexport const ELEMENT_ICON_MARKUP: Readonly<Record<string, string>> = {\n${lines.join("\n")}\n};\n`;
  fs.writeFileSync(OUT, out);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${lines.length} icons)`);
}

#!/usr/bin/env node
// Writes src/lib/infopanel/gauges/icon-markup.generated.ts: each widget icon (src/lib/widget-icons.ts, lucide) as
// its inner SVG markup, rendered here once so the kiosk bundle carries strings instead of React's server renderer.
//   node tools/gen-gauge-icons.mjs
// Run it after changing WIDGET_ICONS or updating lucide-react; tests/lib/infopanel/gauges/icon-markup.test.ts
// fails while the file is stale.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as lucide from "lucide-react";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ICONS_FILE = path.join(ROOT, "src/lib/widget-icons.ts");
const OUT = path.join(ROOT, "src/lib/infopanel/gauges/icon-markup.generated.ts");

/** `name: Component` pairs of WIDGET_ICONS, read from its source (the file is TypeScript). */
export function iconEntries(source = fs.readFileSync(ICONS_FILE, "utf8")) {
  const body = /WIDGET_ICONS[^=]*=\s*\{([^}]*)\}/.exec(source)?.[1];
  if (!body) throw new Error(`no WIDGET_ICONS map in ${ICONS_FILE}`);
  return [...body.matchAll(/(\w+)\s*:\s*(\w+)/g)].map((m) => [m[1], m[2]]);
}

/** The icon's markup without its outer <svg>, exactly as icon-markup.ts produced it at runtime. */
export const innerMarkup = (Icon) =>
  renderToStaticMarkup(createElement(Icon))
    .replace(/^<svg[^>]*>/, "")
    .replace(/<\/svg>$/, "");

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const lines = iconEntries().map(([name, component]) => {
    // biome-ignore lint/performance/noDynamicNamespaceImportAccess: a build-time script; the names come from WIDGET_ICONS.
    const Icon = lucide[component];
    if (!Icon) throw new Error(`lucide-react has no ${component}`);
    return `  ${name}: ${JSON.stringify(innerMarkup(Icon))},`;
  });
  const out = `// Generated by tools/gen-gauge-icons.mjs from src/lib/widget-icons.ts; do not edit.\n// The widget icons' inner SVG markup (lucide, 24 px grid, 2 px round strokes), without the outer <svg>.\n\nexport const GAUGE_ICON_MARKUP: Readonly<Record<string, string>> = {\n${lines.join("\n")}\n};\n`;
  fs.writeFileSync(OUT, out);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${lines.length} icons)`);
}
